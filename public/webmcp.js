function parseUrl(raw) {
	let url;
	try {
		url = new URL(raw);
	} catch {
		fail(`\`${raw}\` is not a valid absolute URL.`);
	}
	const path = url.pathname.replace(/^\/api/, '').replaceAll(/^\/|\/$/g, '');
	const options = {};
	const ignored = [];
	if (path) {
		const [width, height] = path.split('x', 2);
		if (!Number.isFinite(Number(width)) || width === '') {
			fail(`\`${path}\` is not a size path. Expected a path like \`/350\` or \`/350x150\`.`);
		}
		options.width = Number(width);
		// A single-segment path sets both dimensions, which is the part people misread.
		options.height = Number(height === undefined ? width : height);
	}
	for (const [key, value] of url.searchParams) {
		if (!OPTION_ORDER.includes(key)) {
			ignored.push(key);
			continue;
		}
		options[key] = value;
	}
	return { options, ignored };
}

const explainTool = {
	name: 'explain_placeholder_image_url',
	title: 'Explain a Placeholder Image URL',
	description: 'Break an existing placeholders.dev URL into the options it actually uses, filling in the defaults the image API would apply and listing any query parameters it ignores. Useful before editing placeholder URLs already in a codebase.',
	inputSchema: {
		type: 'object',
		properties: {
			url: {
				type: 'string',
				description: 'An absolute placeholders.dev image URL, e.g. `https://images.placeholders.dev/?width=350&text=Hello`.',
				minLength: 1,
			},
		},
		required: ['url'],
	},
	annotations: {
		readOnlyHint: true,
	},
	execute: (input) => {
		const raw = readString(input, 'url') ?? fail('`url` is required.');
		const { options, ignored } = parseUrl(raw);
		const width = Number(options.width ?? 300);
		const height = Number(options.height ?? 150);
		const fontSize = options.fontSize === undefined ? Math.floor(Math.min(width, height) * 0.2) : Number(options.fontSize);
		return Promise.resolve({
			url: raw,
			options,
			resolved: {
				width,
				height,
				text: options.text ?? `${width}×${height}`,
				fontFamily: options.fontFamily ?? 'sans-serif',
				fontWeight: options.fontWeight ?? 'bold',
				fontSize,
				dy: Number(options.dy ?? fontSize * 0.35),
				bgColor: options.bgColor ?? '#ddd',
				textColor: options.textColor ?? 'rgba(0,0,0,0.5)',
				textWrap: options.textWrap === 'true' || options.textWrap === '1',
			},
			...(ignored.length > 0 && { ignoredParameters: ignored }),
		});
	},
};

async function init() {
	if (!window.isSecureContext) {
		return;
	}
	const modelContext = document.modelContext || navigator.modelContext;
	if (!modelContext || typeof modelContext.registerTool !== 'function') {
		return;
	}
	// `registerTool` rejects on validation or duplicate-name errors, so await it to keep
	// failures out of the unhandled-rejection path.
	try {
		await Promise.all([
			modelContext.registerTool(generateTool),
			modelContext.registerTool(explainTool),
		]);
	} catch (err) {
		console.error('WebMCP tool registration failed', err);
	}
}

init();
