// WebMCP integration, exposing placeholder URL tools to visiting AI agents

// Local and staging deploys serve images from `/api` rather than the images subdomain.
function imageBase() {
	if (location.hostname === 'placeholders.dev') {
		return 'https://images.placeholders.dev';
	}
	return `${location.origin}/api`;
}

function fail(message) {
	throw new Error(message);
}

function readString(input, key) {
	const value = input[key];
	if ([undefined, null, ''].includes(value)) {
		return;
	}
	if (typeof value !== 'string') {
		fail(`\`${key}\` must be a string.`);
	}
	return value;
}

function readNumber(input, key, min, max) {
	const value = input[key];
	if (value === undefined || value === null) {
		return;
	}
	if (typeof value !== 'number' || !Number.isFinite(value)) {
		fail(`\`${key}\` must be a number.`);
	}
	if (value < min || value > max) {
		fail(`\`${key}\` must be between ${min} and ${max}, got ${value}.`);
	}
	return value;
}

function readInteger(input, key, min, max) {
	const value = readNumber(input, key, min, max);
	return value === undefined ? undefined : Math.round(value);
}

function readBoolean(input, key) {
	const value = input[key];
	if (value === undefined || value === null) {
		return;
	}
	if (typeof value !== 'boolean') {
		fail(`\`${key}\` must be true or false.`);
	}
	return value;
}

// The API drops any color it cannot parse, so rejecting here tells the agent instead of
// silently handing back a URL that renders with the default grey.
function readColor(input, key) {
	const value = readString(input, key);
	if (value === undefined) {
		return;
	}
	if (!CSS.supports('color', value)) {
		fail(`\`${value}\` is not a valid CSS color for \`${key}\`. Use a hex, rgb(a), hsl(a) or named color.`);
	}
	return value;
}

// The API strips these from `fontFamily` before it reaches the SVG, so a font stack
// containing them would not render as asked.
function readFontFamily(input) {
	const value = readString(input, 'fontFamily');
	if (value !== undefined && /["<>:;]/.test(value)) {
		fail('`fontFamily` cannot contain quotes, angle brackets, colons or semicolons. Pass an unquoted stack like `Inter, sans-serif`.');
	}
	return value;
}

const OPTION_ORDER = [
	'width',
	'height',
	'text',
	'fontFamily',
	'fontWeight',
	'fontSize',
	'dy',
	'bgColor',
	'textColor',
	'darkBgColor',
	'darkTextColor',
	'textWrap',
];

function readOptions(input) {
	return {
		width: readInteger(input, 'width', 1, 10000),
		height: readInteger(input, 'height', 1, 10000),
		text: readString(input, 'text'),
		fontFamily: readFontFamily(input),
		fontWeight: readInteger(input, 'fontWeight', 100, 900),
		fontSize: readInteger(input, 'fontSize', 1, 2000),
		dy: readNumber(input, 'dy', -2000, 2000),
		bgColor: readColor(input, 'bgColor'),
		textColor: readColor(input, 'textColor'),
		darkBgColor: readColor(input, 'darkBgColor'),
		darkTextColor: readColor(input, 'darkTextColor'),
		textWrap: readBoolean(input, 'textWrap'),
	};
}

function buildUrl(options) {
	const base = imageBase();
	const set = OPTION_ORDER.filter(key => options[key] !== undefined);
	// The `/{width}x{height}` shorthand only matches the query form when both are given,
	// since a single-segment path sets height to width.
	if (set.length === 2 && options.width !== undefined && options.height !== undefined) {
		return `${base}/${options.width}x${options.height}`;
	}
	const params = new URLSearchParams();
	for (const key of set) {
		params.set(key, String(options[key]));
	}
	return params.size > 0 ? `${base}/?${params}` : base;
}

function escapeHtml(value) {
	return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;')
		.replaceAll('"', '&quot;');
}

function describeUrl(url, options) {
	const width = options.width ?? 300;
	const height = options.height ?? 150;
	const alt = options.text ?? `${width}x${height} placeholder image`;
	return {
		url,
		width,
		height,
		options,
		html: `<img src="${escapeHtml(url)}" width="${width}" height="${height}" alt="${escapeHtml(alt)}">`,
		markdown: `![${alt}](${url})`,
	};
}

// Puts what the agent built in front of the person watching the page, so they can judge the
// result rather than take the agent's word for it.
function showPreview(result) {
	const section = document.querySelector('#agentPreview');
	const image = document.querySelector('#agentPreviewImage');
	const link = document.querySelector('#agentPreviewUrl');
	if (!section || !image || !link) {
		return;
	}
	image.src = result.url;
	image.width = result.width;
	image.height = result.height;
	image.alt = `${result.width}x${result.height} placeholder image generated by an AI agent`;
	link.href = result.url;
	link.textContent = result.url;
	section.hidden = false;
}

